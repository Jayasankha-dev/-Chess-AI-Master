def evaluate_board(board: chess.Board) -> int:
    """Positive = White advantage; negative = Black advantage."""
    if board.is_checkmate():
        return -100000 if board.turn == chess.WHITE else 100000
    if board.is_stalemate() or board.is_insufficient_material() or board.is_fifty_moves() or board.is_fivefold_repetition():
        return 0

    score = 0
    for square, piece in board.piece_map().items():
        value = PIECE_VALUES[piece.piece_type]
        table = PST[piece.piece_type]
        index = square if piece.color == chess.WHITE else chess.square_mirror(square)
        positional = table[index]
        score += value + positional if piece.color == chess.WHITE else -(value + positional)

    # Small mobility bonus.
    turn = board.turn
    mobility = board.legal_moves.count()
    score += mobility * (3 if turn == chess.WHITE else -3)
    return score
